"""The store's catalog (32.1): ``CATALOG.json`` and ``README.md`` at its root, generated from what is there, and the
store's schemas (every store contract's JSON Schema) beside them, so a file can be read without the code that wrote it.
A copy of the catalog goes to ``training_records/STORE_CATALOG.json`` in this repository (counts, kinds, hashes; never the
data), the R&D repository's view of the store.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Optional

from dclab_core.store import EXAMPLE_SHAPES, KINDS, MODEL_TYPES

from .layout import DEFAULT, ROOT, Layout
from .store import Store, now, write_json

SCHEMAS = ("store_entry", "store_record", "decision_example", "chat_example", "preference_pair", "solver_trajectory", "episode",
           "judged_example", "retrieval_example", "curation_decision", "set_manifest", "capture_rule", "workflow_record", "experiment_record",
           "model_build", "build_verdict", "learning_curve", "knowledge_item", "service_engagement", "playbook_item")
from .layout import CATALOG_COPY as COPY  # noqa: E402


def _sets(layout: Layout) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {m: [] for m in MODEL_TYPES}
    for model_type in MODEL_TYPES:
        base = layout.sets(model_type)
        for manifest in sorted(base.rglob("MANIFEST.json")) if base.exists() else []:
            doc = json.loads(manifest.read_text(encoding="utf-8"))
            reasons = manifest.parent / "REASONING.json"
            out[model_type].append({"name": doc.get("name"), "version": doc.get("version"), "counts": doc.get("counts", {}),
                                    "reasoning": json.loads(reasons.read_text(encoding="utf-8")) if reasons.exists() else None,
                                    "path": layout.relative(manifest.parent)})
    return out


def _quarantine(layout: Layout) -> dict[str, int]:
    base = layout.quarantine()
    return {p.name: sum(1 for _ in p.rglob("*.json*")) for p in sorted(base.iterdir())} if base.exists() else {}


def _costs(layout: Layout) -> dict[str, Any]:
    """32.22: model spend from the shaped model requests: in total, by purpose, and by model type (each request's cost counted for
    every model type its record was placed in)."""
    from . import shapers
    from .sets import standing

    by_purpose: dict[str, float] = {}
    per_record: dict[str, float] = {}
    for r in shapers.records(layout, "model_requests"):
        eur = r.body.get("cost_eur")
        if isinstance(eur, (int, float)):
            by_purpose[str(r.body.get("purpose") or "unknown")] = by_purpose.get(str(r.body.get("purpose") or "unknown"), 0.0) + float(eur)
            per_record[r.id] = float(eur)
    by_model: dict[str, float] = {}
    for (rid, model_type), choice in standing(layout).items():
        if rid in per_record and choice.get("quality") != "out" and not choice.get("refused"):
            by_model[model_type] = by_model.get(model_type, 0.0) + per_record[rid]
    return {"total_eur": round(sum(by_purpose.values()), 6), "by_purpose": {k: round(v, 6) for k, v in sorted(by_purpose.items())},
            "by_model_type": {k: round(v, 6) for k, v in sorted(by_model.items())}}


def build(layout: Optional[Layout] = None) -> dict[str, Any]:
    layout = layout or Layout()
    store = Store(layout)
    from dclab_core.store_rules import RULES, VERSION

    doc = {"schema_version": 1, "built_at": now(), "root": "the store's root (dclab-records, owner/main)", "costs": _costs(layout),
           "kinds": {k: {"what": KINDS[k], **v} for k, v in store.counts().items()},
           "model_types": {m: {"what": MODEL_TYPES[m], "shapes": list(EXAMPLE_SHAPES[m]), "sets": s} for m, s in _sets(layout).items()},
           "quarantine": _quarantine(layout), "capture_rules": {"version": VERSION, "tasks": sorted(RULES)},
           "schemas": [f"schemas/{n}.json" for n in SCHEMAS]}
    try:  # 36.1: the coverage summary is written by `make coverage` (store/coverage.py); a rebuild keeps the last one
        previous = json.loads(layout.catalog.read_text(encoding="utf-8")) if layout.catalog.exists() else {}
    except ValueError:
        previous = {}
    if isinstance(previous.get("coverage"), dict):
        doc["coverage"] = previous["coverage"]
    return doc


README = """# DCLab's store

Everything DCLab keeps for training its models and learning its craft, in three tiers. Generated by
`python -m dclab_rnd.store catalog`; the plan is `docs/guides/STORING_PHASE_PLAN.md` in the R&D repository.

- `raw/<kind>/`: sources kept whole, compressed, append-only; `index.jsonl` lists every kept version with its hash.
- `records/<kind>/`: the same data normalised, one record shape per kind, each with its provenance.
- `sets/<model type>/`: training sets, each with `MANIFEST.json`, `CARD.md` and its train, dev and sealed splits (a sealed
  split is never read to tune anything).
- `quarantine/<reason>/`: records kept out of a set, with the check they failed. They are still whole in `raw/`.
- `service/`: the knowledge of building models for businesses and of giving the service: every build with its verdict,
  the learning curves, the catalog of kinds (aggregates only), the engagements, the playbook and `people.json` (each person's
  sessions and work under a pseudonymous id: never an email, name, password or token).
- `runs/`: every conductor, shaper, curator, builder and tutor run.
- `schemas/`: the JSON Schema of every record and set shape.
- `forgotten/`: the owner's tombstones, never the data.

Deleting a project, a draft or a session in DCLab never removes it from here. Only the owner's audited `store forget` does.

In the repository (`dclab-records`, Git LFS for `raw/**/*.gz` and each set's `sealed.jsonl`): every kept source, the indexes,
the catalog, the schemas, the service records, the runs and quarantine, and each set's manifest, card and sealed split. Not
in it, because they are rebuilt from `raw/`: `records/` (`python -m dclab_rnd.store shape`) and each set's train, dev and
pending splits (`python -m dclab_rnd.store build`; the sealed split is kept, so a sealed row stays sealed after a rebuild).

## Kinds

{kinds}

## Model types

{models}
"""


def write(layout: Optional[Layout] = None, copy: Optional[Path] = None) -> dict[str, Any]:
    """Write ``CATALOG.json``, ``README.md`` and the schemas at the store's root, and the catalog's copy in this repository: only for
    the owner's own store (the default root), or where ``copy`` says (a scratch or tester store never replaces the repository's view)."""
    from dclab_core.contracts import CONTRACTS

    layout = layout or Layout()
    doc = build(layout)
    write_json(layout.catalog, doc)
    for name in SCHEMAS:
        write_json(layout.schema(name), CONTRACTS[name].model_json_schema())
    kinds = "\n".join(f"- `{k}`: {v['what']} ({v['entries']} kept versions of {v['sources']} sources, {v['bytes']:,} bytes)"
                      for k, v in doc["kinds"].items())
    models = "\n".join(f"- `{m}`: {v['what']} ({len(v['sets'])} sets; shapes: {', '.join(v['shapes'])})" for m, v in doc["model_types"].items())
    layout.readme.write_text(README.format(kinds=kinds, models=models), encoding="utf-8")
    if copy is None and layout.root.resolve() == DEFAULT.resolve():
        copy = COPY
    if copy is not None:
        kept = {k: v for k, v in doc.items() if k != "built_at"}  # no time: it changes only when the store does
        if isinstance(kept.get("coverage"), dict):
            kept["coverage"] = {k: v for k, v in kept["coverage"].items() if k != "built_at"}  # 36.1: the coverage summary's time too
        write_json(copy, kept)
    return doc


__all__ = ["build", "write", "SCHEMAS", "COPY"]
