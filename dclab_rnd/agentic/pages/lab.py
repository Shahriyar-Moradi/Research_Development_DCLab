"""Research lab and Benchmark: the R&D itself, read from the repository (read-only).

    GET /api/lab/summary     registry, champions, campaigns, critic gate, pitfalls, auditor headline,
                             research-track statuses and the campaign commands from the Makefile
    GET /api/lab/benchmark   blind auditor replay per dataset, the notebook pilot (when its frozen
                             manifest is committed) and the planned suites and policies, marked planned

Every number comes from a file or a deterministic function in the repository:

- registry and champions: ``registry.collect_registry`` + ``analysis.build_evidence``, the same
  code as ``python -m dclab_rnd status``;
- campaigns: ``evidence/campaigns/*/`` (manifest, immutable result JSONs, report);
- evidence index: ``evidence/knowledge/rag/records.jsonl`` (generated by ``make index``);
- critic gate: ``critic_gate.gate_campaigns`` + ``critic_gate.summary`` (``make critic-gate``);
- pitfalls: ``evidence/campaigns/pitfalls_v1/results/PIT-*.json``;
- blind auditor replay: the stored ``VER-001`` result written by ``make verify-auditor``;
- notebook pilot: ``notebook_assist_eval.evaluate`` on the frozen manifest at its committed home.

Results are cached by the modification times of the files they were read from.
"""

