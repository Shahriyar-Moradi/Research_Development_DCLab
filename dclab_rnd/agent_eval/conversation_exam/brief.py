"""The brief for the writer of a new set of written people: ``python -m dclab_rnd.agent_eval.conversation_exam.brief``.

Generated (``WRITING_PEOPLE.md`` is rebuilt by this command, not edited; ``--check`` fails when it is stale), so the tables it
shows the writer are the tables the exam gives the people. Written after the route test of 2026-11-01: the practice set
``people_dev_route`` was written by a writer who never saw the tables, and at least three of its eight played people with a table
told a story the table could not hold (``table_fit``).
"""

from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BRIEF = HERE / "WRITING_PEOPLE.md"


def tables_section() -> str:
    from . import table_fit as T

    out = []
    for name in T.TABLES:
        f = T.facts(name)
        out += [f"### The `{name}` table ({f['rows']:,} rows)", "", f"Columns: {', '.join(f'`{c}`' for c in f['columns'])}.", ""]
        for column, values in f["values"].items():
            out.append(f"- `{column}` holds only: {', '.join(values)}.")
        for column, (low, high) in f["ranges"].items():
            out.append(f"- `{column}` is a number from {low:g} to {high:g}.")
        for column, (first, last) in f["dates"].items():
            out.append(f"- `{column}` is a date from {first} to {last}.")
        for column, example in f["examples"].items():
            out.append(f"- `{column}` is text; for example `{example}`.")
        out.append(f"- Exact duplicate rows: {f['duplicate_rows'] or 'none'}. Id columns that repeat: "
                   + (", ".join(f"`{c}`" for c in f["repeated"]) or "none") + ". Columns with gaps: "
                   + (", ".join(f"`{c}`" for c in f["missing"]) or "none") + ".")
        out.append("")
    return "\n".join(out)


def render() -> str:
    from . import LEVELS, ROUTE_TRAPS, STYLES, TRAPS, TRUTH, table_fit
    from .arms import TOOLS, TRACKS

    return f"""# Writing the people of a new conversation set

*Generated by `python -m dclab_rnd.agent_eval.conversation_exam.brief` from the exam's own code and tables: do not edit by hand.*

Each person is a short JSON record: who they are, what they would really say, what they hide, what a good listener must
understand, the right kind of help, and sometimes a trap. A separate model plays the person from this record, so the record
is all the exam knows of them. Write the people **for the tables below**, not for any table you imagine.

## The one rule: the story must fit the table

Every person who shares data shares one of the three tables below, exactly as it is. If the story needs data the table does
not hold (other city names, other destinations, a country, duplicates the table lacks), the simulated person will notice,
doubt the file, and drift into "I sent the wrong file". Neither student's behaviour can then be read from the conversation.
In the practice set written without these tables, at least three of eight played people did this.

So: **choose the table first, then write the person who owns it**. A person in Turkey cannot share the UAE `sales` table
unless the story says it is a test export; a tour operator in Peru cannot share the `bookings` table of Paris and Dubai.
Every person with `"upload"` must also carry `"table_claims"`, which says what the story relies on in the table. Code checks
the claims against the real table and refuses the set if one is false:

```json
"table_claims": {{"columns": ["customer_id", "city"],
                  "values": {{"city": ["Dubai", "Sharjah"]}},
                  "duplicate_rows": false,
                  "repeated": ["customer_id"],
                  "unique": ["order_id"],
                  "missing": ["monthly_spend"]}}
```

(`columns`: columns the story names; `values`: values it names, per column (text, numbers and yes/no columns that hold few
values); `duplicate_rows`: whether it says exact duplicate rows exist; `repeated` / `unique`: id columns it says repeat, or
say have one row each; `missing`: columns it says have gaps. Claim what the story uses: an empty `table_claims` is refused.
Amounts, currencies and dates are not claimable, so read their lines below and keep the story inside them: money in the
currency the table shows, events inside the dates it spans.)
A person with no table needs no claims. `check_person(person, require_claims=True)` runs for sets listed in `REQUIRE_CLAIMS`.

## The three tables

{tables_section()}
## The record

- `id`: a short unique id. `level`: one of {', '.join(f'`{x}`' for x in LEVELS)}. `style`: one of {', '.join(f'`{x}`' for x in STYLES)}.
- `opening`: the person's first message, in their own words (no jargon unless their level uses it).
- `upload`: `null` or one of {', '.join(f'`{x}`' for x in table_fit.TABLES)}; then `table_claims` (above).
- `truth`: an object with {', '.join(f'`{x}`' for x in TRUTH)}: all hidden, all in the person's voice; what they do not know, they say they do not know.
- `must_understand`: two to five points a good listener must grasp.
- `route`: the right kind of help, one of {', '.join(f'`{x}`' for x in TRACKS)}; `tool`: one of {', '.join(f'`{x}`' for x in TOOLS)}; `also_right`: other acceptable routes (usually none).
- `trap`: `null` or one of {', '.join(f'`{x}`' for x in TRAPS)}, with `trap_check`: one sentence on what handling it well looks like.

## The mix and the order

- About twelve people for a sealed run (the budget); at least three that are **technical advice with no table** (a data scientist
  asking a method question: these were the costly ones), at least three **clear requests** (`clear_request`) whose table fits
  the request, and the rest spread over the other routes and traps. Real, varied voices; no two people with the same opening.
- A trap of the route kinds ({', '.join(f'`{x}`' for x in ROUTE_TRAPS)}) is passed only when the route is also right, so write the
  route and the trap together.
- To register a new set (a sealed set is run once): add its file to `SPLITS` in `conversation_exam/__init__.py`, its `.sha256` to
  `SEALED` (or `PINNED` for a practice set), its arms to `SEALED_ARMS`, and its gate to `gate.GATES`; then it is refused until every
  person passes `check_person` (claims required for the sets in `REQUIRE_CLAIMS`).
- **Put the hard kinds first** (advice, clear requests, a request for rows): the exam plays people in file order, and a run
  that stops early (a cap, an empty account) should have played the people that decide the question.
- Pin the file with its SHA-256 before its one run (`people_<set>.sha256`); a sealed set is run once and never edited.

## Running it

A run's cap must leave room for one judge request after the last conversation: expected spend plus about a quarter euro. Measured
on the practice runs of 2026-11-01, a conversation costs about EUR 0.1 for the lead agent and 0.05 for Claude alone, plus about 0.02 for the
judge, **but a technical advice conversation costs more**: EUR 0.13 to 0.20 for the lead agent since its length cap (EUR 0.73 before
it) and up to 0.29 for Claude alone. Size the cap for the advice people on their own.
"""


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    text = render()
    if "--check" in argv:
        if not BRIEF.exists() or BRIEF.read_text(encoding="utf-8") != text:
            print(f"{BRIEF.name} is stale: run python -m dclab_rnd.agent_eval.conversation_exam.brief", file=sys.stderr)
            return 1
        print(f"{BRIEF.name} is up to date")
        return 0
    BRIEF.write_text(text, encoding="utf-8")
    print(f"wrote {BRIEF}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
